#!/usr/bin/env node
// Builds the deal-workspace artifacts from the 5 gate-verified bundles:
//   public/deal-index.json   — call metadata + cross-call search records + the
//                               commitment ledger (data only, no logic)
//   public/deal-index.mjs    — a synced copy of src/deal-index.mjs so the deal
//                               workspace (public/index.html) can import the
//                               same search function the tests run against
//                               (single source of truth, copied not
//                               reimplemented)
//   public/calls/NN.html     — one self-contained receipts page per call,
//                               generated by src/export.js's tier1Html(), i.e.
//                               the SAME viewer.js renderer already shipped —
//                               nothing about the per-call view is rebuilt here
//
// Usage: node scripts/build-deal-index.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { buildDealIndex, buildCommitmentLedger } from '../src/deal-index.mjs';
import { tier1Html } from '../src/export.js';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const BUNDLES_DIR = join(ROOT, 'samples/bundles');
const PUBLIC_DIR = join(ROOT, 'public');
const CALLS_DIR = join(PUBLIC_DIR, 'calls');

export function loadBundles(dir = BUNDLES_DIR) {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.bundle.json'))
    .sort();
  if (files.length === 0) {
    throw new Error(`no *.bundle.json files found in ${dir}`);
  }
  return files.map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')));
}

export function build(dir = BUNDLES_DIR) {
  const bundles = loadBundles(dir);
  const index = buildDealIndex(bundles);
  const commitments = buildCommitmentLedger(bundles);
  return { bundles, index, commitments };
}

// The whole deal-workspace build as a callable function (same reason as
// build-notes.mjs's buildNotes): `npm start` refreshes a stale workspace
// in-process rather than shelling out to a second node.
export function buildDealWorkspace({ quiet = false } = {}) {
  const { bundles, index, commitments } = build();

  mkdirSync(CALLS_DIR, { recursive: true });

  writeFileSync(
    join(PUBLIC_DIR, 'deal-index.json'),
    JSON.stringify({ calls: index.calls, records: index.records, commitments }, null, 2),
  );

  copyFileSync(join(ROOT, 'src/deal-index.mjs'), join(PUBLIC_DIR, 'deal-index.mjs'));

  for (const bundle of bundles) {
    const id = bundle.call?.id;
    if (!id) throw new Error('bundle missing call.id — cannot name its export');
    writeFileSync(join(CALLS_DIR, `${id}.html`), tier1Html(bundle));
  }

  if (!quiet) {
    console.log(
      `deal index: ${index.calls.length} calls, ${index.records.length} searchable records, ` +
        `${commitments.length} commitment-ledger entries`,
    );
    console.log(
      `wrote public/deal-index.json, public/deal-index.mjs, and public/calls/{${bundles
        .map((b) => b.call.id)
        .join(',')}}.html`,
    );
  }
  return { calls: index.calls.length, records: index.records.length, commitments: commitments.length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  buildDealWorkspace();
}
